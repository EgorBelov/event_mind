        doc,
        "«Bayesian Thompson работает на уровне тем — у него один alpha/beta на тему. "
        "LinUCB работает на уровне «контекста» — 16-мерного вектора признаков "
        "(пользователь × событие). У каждого пользователя своя матрица A (16×16) и "
