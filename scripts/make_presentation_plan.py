def set_base_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)


def h1(doc: Document, text: str) -> None:
    p = doc.add_heading(text, level=1)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x68)


def h2(doc: Document, text: str) -> None:
    p = doc.add_heading(text, level=2)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x2C, 0x55, 0x82)


def h3(doc: Document, text: str) -> None:
    p = doc.add_heading(text, level=3)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x3B, 0x6E, 0xA8)


def para(doc: Document, text: str, bold: bool = False, italic: bool = False) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic


def bullet(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style="List Bullet")


def numbered(doc: Document, text: str) -> None:
    doc.add_paragraph(text, style="List Number")


def kv_para(doc: Document, key: str, value: str) -> None:
    """Параграф вида «Жирный заголовок: обычный текст»."""
    p = doc.add_paragraph()
    r = p.add_run(f"{key}: ")
    r.bold = True
    p.add_run(value)


def script_block(doc: Document, what_show: str, what_say: str, what_happens: str | None = None) -> None:
    """Блок «что показать / что говорить / что в этот момент происходит под капотом»."""
    kv_para(doc, "Что показать на экране", what_show)
    kv_para(doc, "Что говорить вслух", what_say)
    if what_happens:
        kv_para(doc, "Что на самом деле происходит под капотом (для понимания)", what_happens)


def term_block(doc: Document, term: str, plain: str, why: str, how_to_say: str) -> None:
    """Карточка термина: простое определение + зачем + как сказать вслух."""
    h3(doc, term)
    kv_para(doc, "Простыми словами", plain)
    kv_para(doc, "Зачем это в проекте", why)
    kv_para(doc, "Если спросят — можно сказать так", how_to_say)


def two_col_table(doc: Document, header: tuple[str, str], rows: list[tuple[str, str]]) -> None:
    table = doc.add_table(rows=1, cols=2)
    table.style = "Light Grid Accent 1"
    hdr = table.rows[0].cells
    hdr[0].text = header[0]
    hdr[1].text = header[1]
    for a, b in rows:
        row = table.add_row().cells
        row[0].text = a
        row[1].text = b


def three_col_table(doc: Document, header: tuple[str, str, str], rows: list[tuple[str, str, str]]) -> None:
    table = doc.add_table(rows=1, cols=3)
    table.style = "Light Grid Accent 1"
    hdr = table.rows[0].cells
    for i, h in enumerate(header):
        hdr[i].text = h
    for r in rows:
        row = table.add_row().cells
        for i, v in enumerate(r):
            row[i].text = v


