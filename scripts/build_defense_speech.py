def build(out: str):
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)

    title = doc.add_paragraph()
    r = title.add_run("Текст выступления на защите курсовой работы")
    r.bold = True
    r.font.size = Pt(16)
    r.font.color.rgb = NAVY
    sub = doc.add_paragraph()
    r = sub.add_run("EventMind — агрегация IT-мероприятий и персонализированные "
                    "AI-рекомендации\nОриентир: 15–20 минут")
    r.italic = True
    r.font.size = Pt(12)
    doc.add_paragraph()

    for head, body in SPEECH:
        ph = doc.add_paragraph()
        r = ph.add_run(head)
        r.bold = True
        r.font.size = Pt(14)
        r.font.color.rgb = NAVY
        bp = doc.add_paragraph(body)
        bp.paragraph_format.space_after = Pt(10)

    Path(out).parent.mkdir(parents=True, exist_ok=True)
    doc.save(out)
    print(f"saved: {out}  ({len(SPEECH)} слайдов)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/Текст_выступления_EventMind.docx")
    args = ap.parse_args()
    build(args.out)
