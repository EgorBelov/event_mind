# ─── Удаление ранее вставленной главы ─────────────────────────────────────


def _strip_previous_section(doc):
    """Удаляет всё, начиная с H1, в первом следующем за которым параграфе
    встречается ANCHOR, и до конца документа. Так повторный запуск
    переписывает главу полностью (включая её H1-заголовок), не плодя дубликаты.

    Также удаляет таблицы, идущие после стартового H1 (через body element).
    """
    body = doc.element.body
    paragraphs = list(doc.paragraphs)

    anchor_idx = None
    for i, par in enumerate(paragraphs):
        if ANCHOR in par.text:
            anchor_idx = i
            break
    if anchor_idx is None:
        return

    # Откатимся вверх к ближайшему H1 — он и есть начало нашей главы.
    start_idx = anchor_idx
    for j in range(anchor_idx - 1, -1, -1):
        if (paragraphs[j].style and paragraphs[j].style.name == "H1"):
            start_idx = j
            break

    start_par_element = paragraphs[start_idx]._element

    # Удаляем все sibling-элементы body начиная со start_par_element и до
    # конца — КРОМЕ финального sectPr (свойства секции, без него документ
    # ломается: docx.Document падает на sections[-1]).
    to_remove = []
    found = False
    for child in list(body):
        tag = child.tag.rsplit("}", 1)[-1]
        if child is start_par_element:
            found = True
        if found and tag != "sectPr":
            to_remove.append(child)
    for el in to_remove:
        body.remove(el)


