def _style_run(run, *, size=11, bold=False, italic=False, color=None):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color


def build(out_path: Path) -> None:
    doc = Document()

    # Заголовок документа
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title.add_run("Вероятные вопросы комиссии и ответы")
    _style_run(r, size=20, bold=True, color=NAVY)

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = sub.add_run(
        "EventMind — агрегация IT-мероприятий и персональные рекомендации"
    )
    _style_run(r, size=12, italic=True, color=GREY)

    intro = doc.add_paragraph()
    r = intro.add_run(
        "Сборник вопросов, которые с высокой вероятностью может задать "
        "комиссия, с готовыми развёрнутыми ответами. Сгруппирован по темам — "
        "от общей мотивации до архитектуры, рекомендателя, LLM, оценки "
        "качества и слабых мест. Ответы опираются на реальную реализацию "
        "проекта."
    )
    _style_run(r, size=10, italic=True, color=GREY)

    total = sum(len(qs) for _, qs in SECTIONS)
    cnt = doc.add_paragraph()
    r = cnt.add_run(f"Всего вопросов в документе: {total}.")
    _style_run(r, size=10, italic=True, color=GREY)

    n = 0
    for section_title, qa in SECTIONS:
        h = doc.add_paragraph()
        h.space_before = Pt(10)
        r = h.add_run(section_title)
        _style_run(r, size=14, bold=True, color=NAVY)

        for q, a in qa:
            n += 1
            pq = doc.add_paragraph()
            rq = pq.add_run(f"Q{n}. {q}")
            _style_run(rq, size=11, bold=True)

            pa = doc.add_paragraph()
            ra = pa.add_run(a)
            _style_run(ra, size=11)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(out_path))
    print(f"Saved {n} Q&A to {out_path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--out",
        default="docs/Вопросы_и_ответы_EventMind.docx",
        type=Path,
    )
    args = ap.parse_args()
    build(args.out)


if __name__ == "__main__":
    main()
